// The server's Hebrew label when it sent one; otherwise this table. A label
// that is the key itself (e.g. "salaries") is not a label.
export function categoryLabel(key: string | null | undefined, serverLabel?: string | null): string {
  const text = (key ?? '').trim();
  const sent = (serverLabel ?? '').trim();
  if (sent && sent !== text && !/^[a-z0-9_]+$/.test(sent)) return sent;
  return CATEGORY_LABELS[text] ?? CATEGORY_LABELS[text.toLowerCase()] ?? (sent || text);
}
